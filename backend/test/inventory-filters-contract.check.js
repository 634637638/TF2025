const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

test('inventory list and overview stats use the same filter builder', () => {
  const route = fs.readFileSync(path.join(__dirname, '../src/routes/inventory.js'), 'utf8')
  const controller = fs.readFileSync(path.join(__dirname, '../src/controllers/inventory.controller.js'), 'utf8')
  const service = fs.readFileSync(path.join(__dirname, '../src/services/inventory.service.js'), 'utf8')
  const repository = fs.readFileSync(path.join(__dirname, '../src/repositories/inventory.repository.js'), 'utf8')
  const listStart = route.indexOf("router.get('/list'")
  const overviewStart = route.indexOf("router.get('/stats/overview'")
  const statsStart = route.indexOf("router.get('/stats'")
  assert.ok(listStart >= 0 && overviewStart > listStart && statsStart > overviewStart)
  assert.match(route, /inventoryController\.list\.bind\(inventoryController\)/)
  assert.match(route, /inventoryController\.overview\.bind\(inventoryController\)/)
  assert.match(controller, /this\.service\.list\(req\.query\)/)
  assert.match(controller, /this\.service\.overview\(req\.query\)/)
  assert.match(service, /this\.repository\.listFilters\(query, \{ includeLegacyDate: true \}\)/)
  assert.match(service, /this\.repository\.listFilters\(query\)/)
  assert.match(repository, /const buildInventoryFilters =/)
  assert.match(repository, /p\.store_id = \?/)
  assert.match(repository, /p\.inventory_operator_id = \?/)
  assert.match(repository, /isPhoneStatusAlias\(searchStr\)/)
  assert.match(repository, /if \(includeLegacyDate && date\)/)
  assert.match(repository, /\$\{effectiveStatusSql\} AS status/)
  assert.doesNotMatch(controller, /buildInventoryFilters|whereConditions\.push\(/)
  assert.doesNotMatch(service, /buildInventoryStatsWhere/)
})
