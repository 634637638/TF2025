const extensions = new Set(['.css', '.scss']);
const sourceFiles = [];

function collect(directory) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const entryPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      collect(entryPath);
      continue;
    }
    if (extensions.has(path.extname(entry.name)) || (all && path.extname(entry.name) === '.vue')) {
      sourceFiles.push(entryPath);
    }
  }
}

collect(path.join(root, 'styles'));
collect(path.join(root, 'assets', 'css'));
sourceFiles.push(path.join(root, 'styles.scss'));
if (all) collect(root);

function replaceColors(block) {
  return block.split('\n').map(line => {
    // CSS custom properties are palette declarations, not usage sites.
    if (/^\s*--[a-z0-9_-]+\s*:/.test(line)) return line;

    let next = line;
    for (const [literal, variable] of colorVariables) {
      const escapedLiteral = literal.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      next = next.replace(new RegExp(`${escapedLiteral}(?![0-9a-f])`, 'gi'), variable);
    }
    return next;
  }).join('\n');
}

let changedFiles = 0;
let replacements = 0;

for (const file of [...new Set(sourceFiles)]) {
  if (!fs.existsSync(file)) continue;
  const original = fs.readFileSync(file, 'utf8');
  const transformed = path.extname(file) === '.vue'
    ? original.replace(/(<style\b[^>]*>)([\s\S]*?)(<\/style>)/gi, (_match, open, block, close) => `${open}${replaceColors(block)}${close}`)
    : replaceColors(original);
  if (transformed === original) continue;

  const colorPattern = /#(?:[0-9a-f]{3}|[0-9a-f]{4}|[0-9a-f]{6}|[0-9a-f]{8})(?![a-z0-9_-])/gi;
  const before = (original.match(colorPattern) || []).length;
  const after = (transformed.match(colorPattern) || []).length;
  replacements += Math.max(0, before - after);
  changedFiles += 1;
  if (write) fs.writeFileSync(file, transformed);
}

const scopeLabel = all ? 'style blocks' : 'shared stylesheet files';
console.log(`${write ? 'Updated' : 'Would update'} ${changedFiles} ${scopeLabel} (${replacements} color literals).`);
